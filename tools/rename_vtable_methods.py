#!/usr/bin/env python3
"""Rename vtable method functions to Vtable0x<addr>_m<slot> names.

Source of truth: docs/data-vtables.tsv (generated by analyze_data_structures.py),
one row per method slot:  vtable_addr, slot, fn_or_raw, suggested_name.

Default (matched-only, M6.83): only functions that are MATCHED
(src/fn_XXXX.c exists) are renamed - the M6.76 script-command policy.
With --all: EVERY non-raw vtable method is renamed in symbols.txt even when
not matched yet (same policy as rename_script_cmds.py --all, M6.87), so
future matches auto-name and wip drafts show the vtable method name.

Collision handling: the same fn can occupy many vtable slots (e.g. fn_80256020
is a shared handler at slots 0/5/10 of vtable 0x8030804C). A function can only
carry ONE symbol name, so first-wins by (vtable_addr, slot) order -- the first
vtable slot that references a fn claims it; later slots keep the same name
(they already point at the renamed symbol, so no work is needed).

Per renamed fn (identical mechanics to tools/rename_script_cmds.py):
  1. symbols.txt : fn_XXXX -> Vtable0x<addr>_m<slot> (+ scope:global)
  2. src/fn_XXXX.c (when matched): rename the definition symbol + insert
     '// Name @ 0xADDR'
  3. all src/*.c and src/wip/*.c : word-boundary rename of callers/externs
Filenames stay address-based. Idempotent: already-Vtable-prefixed symbols are
skipped. Raw mid-function pointers (0x8025C590) are never renamed - they have
no fn_ symbol. M6.87 regression guard: only accept syms matching
^fn_[0-9A-F]{8}$ so malformed/placeholder values can never enter the map.

Usage:  tools/venv/bin/python tools/rename_vtable_methods.py [--all]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

ALL = "--all" in sys.argv

# ---- 1. build rename map from the vtable TSV (first-wins) ----
claimed = {}  # fn_sym -> (new_name, addr)
for line in open("docs/data-vtables.tsv"):
    if line.startswith("#") or not line.strip():
        continue
    p = line.rstrip("\n").split("\t")
    if len(p) < 4:
        continue
    vaddr, slot, fn, sugg = p
    # M6.87 guard, inline (parity with rename_script_cmds.py): only well-formed
    # fn_ symbols with a non-empty suggested name can be renamed. Rejects raw
    # mid-function pointers (0x8025C590), the TSV header row ('fn_or_raw'), and
    # any malformed/placeholder value - the M6.87 regression class.
    if not re.match(r"^fn_[0-9A-F]{8}$", fn) or not sugg.strip():
        continue
    if fn in claimed:
        continue  # already claimed by an earlier vtable slot
    claimed[fn] = (sugg, "0x" + fn.split("_", 1)[1])

if ALL:
    rename = dict(claimed)
    skipped = set()
else:
    # only matched functions (src file exists) are renameable
    rename = {fn: v for fn, v in claimed.items() if os.path.exists("src/%s.c" % fn)}
    skipped = {fn for fn in claimed if fn not in rename}

print("vtable slots total:    ", sum(1 for _ in open("docs/data-vtables.tsv") if not _.startswith("#") and _.strip()))
print("unique fns in vtables: ", len(claimed))
print("renaming (%s):    " % ("--all" if ALL else "matched-only"), len(rename))
print("skipped:               ", len(skipped))
for fn in sorted(rename):
    print("   %s -> %s" % (fn, rename[fn][0]))

# ---- 2. symbols.txt ----
symlines = open("config/G2TE52/symbols.txt").read().splitlines(keepends=True)
changed = 0
out = []
for ln in symlines:
    m = re.match(r"^(fn_[0-9A-F]{8}) = (\S+); // (.*)$", ln.rstrip("\n"))
    if m and m.group(1) in rename:
        name, addr = rename[m.group(1)]
        assert name != m.group(1), "self-rename?!"
        rest = m.group(3)
        if "scope:global" not in rest:
            rest = rest.rstrip() + " scope:global"
        out.append("%s = %s; // %s\n" % (name, m.group(2), rest))
        changed += 1
    else:
        out.append(ln)
open("config/G2TE52/symbols.txt", "w").writelines(out)
print("symbols.txt lines changed:", changed)

# ---- 3. source renames: word-boundary replace in src + wip ----
syms = list(rename.keys())
pat = re.compile(r"\b(" + "|".join(re.escape(s) for s in syms) + r")\b")


def rewrite(fp):
    t = open(fp).read()

    def sub(m):
        return rename[m.group(1)][0]

    t2, n = pat.subn(sub, t)
    if n:
        open(fp, "w").write(t2)
    return n


src_files = ["src/%s" % f for f in sorted(os.listdir("src")) if f.endswith(".c")]
wip_files = ["src/wip/%s" % f for f in sorted(os.listdir("src/wip")) if f.endswith(".c")]
src_hit = [fp for fp in src_files if pat.search(open(fp).read())]
wip_hit = [fp for fp in wip_files if pat.search(open(fp).read())]
print("src files to touch:", len(src_hit), " wip files to touch:", len(wip_hit))

total = 0
for fp in src_hit + wip_hit:
    total += rewrite(fp)
print("total token replacements:", total)

# ---- 4. address comments above each definition (matched files only) ----
for sym, (name, addr) in rename.items():
    fp = "src/%s.c" % sym
    if not os.path.exists(fp):
        continue  # unmatched: renamed in symbols.txt only
    t = open(fp).read()
    lines = t.splitlines(keepends=True)
    idx = None
    for i, ln in enumerate(lines):
        if re.search(r"\b%s\s*\(" % re.escape(name), ln):
            idx = i
            break
    if idx is None:
        print("WARN: no definition line for", sym, name)
        continue
    comment = "// %s @ %s\n" % (name, addr)
    if idx > 0 and comment.strip() in lines[idx - 1]:
        continue
    lines.insert(idx, comment)
    open(fp, "w").writelines(lines)

print("done")
