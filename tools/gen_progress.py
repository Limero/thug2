#!/usr/bin/env python3
"""
Generate PROGRESS.md (the function-by-function decomp checklist) from
build/G2TE52/report.json.

Regenerate after matching new functions:
    tools/ninja build/tools/objdiff-cli   # only if objdiff-cli was wiped (cold rebuild)
    build/tools/objdiff-cli report generate -o build/G2TE52/report.json
    tools/venv/bin/python tools/gen_progress.py

The checklist is grouped by split unit (source file / extracted object).
Each function row: `- [x]` = 100% fuzzy match, `- [ ]` = still assembly.
"""
import json
import sys
from datetime import datetime
from pathlib import Path

REPORT = Path("build/G2TE52/report.json")
OUT = Path("PROGRESS.md")
SHA = Path("config/G2TE52/build.sha1")


def is_matched(f: dict) -> bool:
    """Strict matches field wins; fall back to 100% fuzzy."""
    if "matches" in f:
        return bool(f["matches"])
    return f.get("fuzzy_match_percent", 0) >= 100


def walk(items):
    for u in items:
        if "units" in u:
            yield from walk(u["units"])
        else:
            yield u


def main() -> int:
    if not REPORT.is_file():
        print(f"missing {REPORT} — run objdiff-cli report generate first")
        return 1
    with open(REPORT) as f:
        r = json.load(f)
    m = r.get("measures", {})
    units = list(walk(r.get("units", [])))

    total_fns = int(m.get("total_functions", 0))
    matched_fns = int(m.get("matched_functions", 0))
    total_code = int(m.get("total_code", 0) or 0)
    matched_code = int(m.get("matched_code", 0) or 0)
    pct_fns = 100.0 * matched_fns / total_fns if total_fns else 0.0
    pct_code = 100.0 * matched_code / total_code if total_code else 0.0

    lines = []
    A = lines.append
    A("# THUG2 (G2TE52) Decomp Progress\n")
    A(f"_Auto-generated by `tools/gen_progress.py` — do not edit by hand. Last generated: {datetime.now():%Y-%m-%d %H:%M}_\n")
    A("## Summary\n")
    A("| Metric | Value |")
    A("|---|---|")
    A(f"| Functions matched | **{matched_fns} / {total_fns}** ({pct_fns:.3f}%) |")
    A(f"| Code bytes matched | {matched_code} / {total_code} ({pct_code:.4f}%) |")
    A(f"| Source units complete | {m.get('complete_units', 0)} / {m.get('total_units', 0)} |")
    dol_hash = "(read config/G2TE52/build.sha1)"
    if SHA.is_file():
        with open(SHA) as f:
            first = f.read().strip().split()[0]
        if len(first) == 40:
            dol_hash = first
    A(f"| DOL hash | `{dol_hash}` (must stay identical) |")
    A("")

    # Per-unit table
    A("## Source units\n")
    A("| Unit | Functions | Matched | Status |")
    A("|---|---|---|---|")
    for u in sorted(units, key=lambda x: x.get("name", "")):
        fns = u.get("functions", [])
        mf = sum(1 for f in fns if is_matched(f))
        comp = u.get("metadata", {}).get("complete")
        name = u.get("name", "?")
        if name.startswith("main/"):
            name = name[5:]
        if len(fns) == 0:
            status = "— (data only)"
        elif comp:
            status = "✅ complete"
        elif mf:
            status = "⬜ in progress"
        else:
            status = "⏳ assembly"
        A(f"| `{name}` | {len(fns)} | {mf} | {status} |")
    A("")

    # Full function checklist, grouped by unit
    A("## Function checklist\n")
    A("`- [x]` = matched (100%), `- [ ]` = still assembly\n")
    for u in sorted(units, key=lambda x: x.get("name", "")):
        fns = u.get("functions", [])
        if not fns:
            continue
        name = u.get("name", "?")
        if name.startswith("main/"):
            name = name[5:]
        src = u.get("metadata", {}).get("source_path")
        src_note = f" → `{src}`" if src else ""
        A(f"### {name}{src_note}\n")
        # address/size are STRINGS in report.json — cast to int for numeric order
        for f in sorted(fns, key=lambda x: int(x.get("address", 0) or 0)):
            fname = f.get("name", "?")
            size = f.get("size", "?")
            if is_matched(f):
                A(f"- [x] `{fname}` ({size}B)")
            else:
                A(f"- [ ] `{fname}` ({size}B)")
        A("")

    A("## Regenerating\n")
    A("```sh")
    A("tools/ninja build/tools/objdiff-cli   # only if objdiff-cli was wiped (cold rebuild)")
    A("build/tools/objdiff-cli report generate -o build/G2TE52/report.json")
    A("tools/venv/bin/python tools/gen_progress.py")
    A("```")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({total_fns} functions, {matched_fns} matched)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
