    /* 0x801AC8B4..0x801AC8E0 */
    dir = 0;
    if (hitA != 0) {
        if (hitB == 0) {
            dir = -1;
        }
    } else if (hitB != 0) {
        dir = 1;
    }

    /* 0x801AC8E0..0x801AC948: signed-distance style test, flips the direction
       when the plane value falls below lbl_802ABBE8. */
