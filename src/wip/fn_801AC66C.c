/* An 8-byte paired-single value; the retail code reads the two halves both as
   a pair (psq_l/psq_st/ps_*) and as single floats (lfs/stfs/fcmpu), which is
   exactly what a union of __ps_t and f32[2] gives. */
typedef union {
    __ps_t p;
    struct {
        f32 lo, hi;
    } f;
} Pair;

/* arg0: two points at +0x28/+0x30 and a pointer at +0x48. */
typedef struct {
    u8 pad00[0x28];
    Pair pl;                /* +0x28 */
    Pair ph;                /* +0x30 */
    u8 pad38[0x10];
    void *src;              /* +0x48 */
} Plane;

/* the object arg0->src points at: two more points at +0x28/+0x30 */
typedef struct {
    u8 pad00[0x28];
    Pair a;                 /* +0x28 */
    Pair b;                 /* +0x30 */
} PlaneSrc;

/* arg1: two points at +0x00/+0x08 */
typedef struct {
    Pair a;                 /* +0x00 */
    Pair b;                 /* +0x08 */
} Axis;

/* Scratch object filled in by fn_8010794C and consumed by fn_80107AB4 /
   fn_80107B20.  Only the members the want touches are named; the leading
   four pairs are the four points and +0xA8 is the CObject ref-link the
   epilogue detaches.  NOTE: the true extent is not known from the DAS only
   (the ctor fills the rest through the pointer). */
typedef struct {
    Pair p0;                /* +0x00 (sp+0x28) */
    Pair p1;                /* +0x08 (sp+0x30) */
    Pair p2;                /* +0x10 (sp+0x38) */
    Pair p3;                /* +0x18 (sp+0x40) */
    u8 pad20[0x88];
    void *refLink;          /* +0xA8 (sp+0xD0) */
    u8 padAC[0x3C];
} Query;

/* Locals, named after the frame offsets the want actually uses.  The holes
   (the Query at 0x28..0xE7 and the float scratch at 0xEC/0xF8/0xFC/0x100/
   0x144/0x148) are laid out so the byte offsets above are reproduced. */
typedef struct {
    Pair v08;               /* +0x08 */
    Pair v10;               /* +0x10 */
    Pair v18;               /* +0x18 */
    Pair v20;               /* +0x20 */
    Query q;                /* +0x28 */
    Pair v0E8;              /* +0xE8 */
    Pair v0F0;              /* +0xF0 */
    Pair v0F8;              /* +0xF8 */
    Pair v100;              /* +0x100 */
    Pair v108;              /* +0x108 */
    Pair v110;              /* +0x110 */
    Pair v118;              /* +0x118 */
    Pair v120;              /* +0x120 */
    Pair v128;              /* +0x128 */
    Pair v130;              /* +0x130 */
    Pair v138;              /* +0x138 */
    Pair v140;              /* +0x140 */
    Pair v148;              /* +0x148 */
} Frame;

